#!/usr/bin/env python3
"""Paired OrcaSlicer -> OpenSnorca rewrite of gettext strings (docs/records/rebrand-opensnorca.md, slice 3).

The product name inside a gettext literal is part of the msgid, so changing only the C++ literal would silently
drop that string's translations. This script changes the source literal AND, in every localization/i18n .pot/.po
entry whose msgid has the same text, the msgid and the msgstr, so lookups keep matching and every translation stays valid.

  rebrand_strings.py            dry run: print what would change and any mismatch between source and catalogs
  rebrand_strings.py --apply    rewrite src/ and localization/i18n/

Only catalog entries whose msgid also occurs as a changed source literal are rewritten; the daily-tip texts
(resources/data/hints.ini, translated through the same catalogs) still say OrcaSlicer/Orca Slicer.

Strings that refer to the upstream project (credits, upstream release facts) are excluded by KEEP.
Not changed: the gettext domain ("OrcaSlicer", the .po/.mo file names).
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NEW = "OpenSnorca"
TOKEN = re.compile(r"OrcaSlicer|Orca Slicer")
# Substrings of strings that name the upstream project on purpose.
KEEP = [
    "began in that same spirit", "Today, OrcaSlicer is", "Pte Ltd", "is licensed under", "is based on PrusaSlicer",
    "not developed or maintained by", "restructured many system filament", "Since version 2.4.0",
    "2.3.1-alpha", "generated by an old OrcaSlicer", "Orca Slicer Beta", "Test OrcaSlicer (GitHub)",
    "The firmware version is abnormal",  # source has a \\? escape the catalogs do not, so the msgids would not match
]
CALL = re.compile(r'\b(?:_L|L|_u8L|_CTX|_CTX_utf8|_utf8|_L_PLURAL|_)\(\s*((?:"(?:[^"\\]|\\.)*"\s*)+)')
LIT = re.compile(r'"((?:[^"\\]|\\.)*)"')


def joined(lits: str) -> str:
    return "".join(LIT.findall(lits))


def wanted(text: str) -> bool:
    return bool(TOKEN.search(text)) and not any(k in text for k in KEEP)


def main() -> int:
    apply = "--apply" in sys.argv
    src_old_new = {}
    for f in sorted((ROOT / "src").rglob("*")):
        if f.suffix not in (".cpp", ".hpp", ".h", ".mm"):
            continue
        txt = f.read_text(encoding="utf-8")

        def repl(m):
            if not wanted(joined(m.group(1))):
                return m.group(0)
            new_lits = LIT.sub(lambda lm: '"' + TOKEN.sub(NEW, lm.group(1)) + '"', m.group(1))
            src_old_new[joined(m.group(1))] = joined(new_lits)
            return m.group(0)[: m.start(1) - m.start(0)] + new_lits

        out = CALL.sub(repl, txt)
        if out != txt and apply:
            f.write_text(out, encoding="utf-8")

    cat_changed = set()
    for f in sorted((ROOT / "localization" / "i18n").rglob("*")):
        if f.suffix not in (".po", ".pot"):
            continue
        lines = f.read_text(encoding="utf-8").split("\n")
        out, block = [], []

        def flush():
            if not block:
                return
            msgid, in_id = "", False
            for ln in block:
                if ln.startswith("msgid "):
                    in_id = True; msgid = "".join(LIT.findall(ln))
                elif ln.startswith(("msgid_plural", "msgstr")):
                    in_id = False
                elif in_id and ln.startswith('"'):
                    msgid += "".join(LIT.findall(ln))
            if wanted(msgid) and msgid in src_old_new:
                cat_changed.add(msgid)
                for ln in block:
                    out.append(TOKEN.sub(NEW, ln) if ln.startswith(("msgid", "msgstr", '"')) else ln)
            else:
                out.extend(block)
            block.clear()

        for ln in lines:
            if ln.strip() == "":
                flush(); out.append(ln)
            else:
                block.append(ln)
        flush()
        if apply:
            f.write_text("\n".join(out), encoding="utf-8")

    only_src = sorted(set(src_old_new) - cat_changed)
    only_cat = sorted(cat_changed - set(src_old_new))
    print("source literals changed: %d; catalog msgids changed: %d" % (len(src_old_new), len(cat_changed)))
    print("in source but not in any catalog (new string, untranslated): %d" % len(only_src))
    for s in only_src: print("  SRC-ONLY:", s[:100])
    print("in catalogs but no source literal changed (would lose its source match): %d" % len(only_cat))
    for s in only_cat: print("  CAT-ONLY:", s[:100])
    return 0


if __name__ == "__main__":
    sys.exit(main())
